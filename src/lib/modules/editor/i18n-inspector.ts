type Words = typeof en;

/** A source's name in the current language — sourceLabel, translated. */
export const sourceName = (t: Words, id: number) => {
  const label = ID_LABELS[id];

  if (label) return (t.ids as Record<string, string>)[label] ?? label;
  return isSlotSel(id) ? t.slotSel(id - SLOT_SEL_ID) : sourceLabel(id);
};

/** What a source picker shows — pickerLabel, translated (the "(0x..)" suffix is kept). */
export const sourcePick = (t: Words, id: number) => {
  if (!id) return t.noneStatic;
  const label = ID_LABELS[id];

  return label ? pickerLabel(id).replace(label, sourceName(t, id)) : sourceName(t, id);
};

/** describeConditions, translated. */
export const conditionLines = (t: Words, conditions: readonly Condition[]) =>
  conditions.map(({ source, op, value }) => t.cond[op](sourceName(t, source), value));
